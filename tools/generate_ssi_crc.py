#!/usr/bin/env python3
"""Generate exact CRC-16/CCITT-FALSE word-update tables for both processors."""
from pathlib import Path
import struct

ROOT = Path(__file__).resolve().parents[1]


def advance(crc, bits):
    for _ in range(bits):
        crc = ((crc << 1) ^ (0x1021 if crc & 0x8000 else 0)) & 0xffff
    return crc


def generate():
    tables = {8: [advance(i << 8, 8) for i in range(256)],
              16: [advance(i << 8, 16) for i in range(256)]}
    # Exhaust all XOR inputs, including the DSP's signed MPY byte extraction.
    for value in range(65536):
        signed = (value << 8) - (0x1000000 if value & 0x8000 else 0)
        high = (signed * 128 * 2 >> 24) & 255
        low = (signed * 32768 * 2 >> 24) & 255
        assert (high, low) == (value >> 8, value & 255)
        assert tables[16][high] ^ tables[8][low] == advance(value, 16)
    cpu = [advance(i, 16) for i in range(65536)]
    (ROOT / 'TREX/m68030/ssi_crc_table.bin').write_bytes(struct.pack('>65536H', *cpu))
    (ROOT / 'TREX/m68030/ssi_crc_table.i').write_text(
        '; Generated by tools/generate_ssi_crc.py; CRC-16/CCITT-FALSE.\n'
        '; word_table[CRC XOR unit], indexed with a zero high word.\n'
        'ssi_packet_crc_word_table:\n'
        '\tincbin "TREX/m68030/ssi_crc_table.bin"\n')
    lines = ['; Generated by tools/generate_ssi_crc.py; CRC-16/CCITT-FALSE.',
             '; T16[high(CRC XOR unit)] XOR T8[low(CRC XOR unit)], aligned <<8.']
    for bits, table in tables.items():
        lines.append('ssi_crc_table' + str(bits) + ':')
        for offset in range(0, len(table), 8):
            lines.append('\tdc\t' + ','.join('$%06x' % (v << 8)
                                            for v in table[offset:offset + 8]))
    (ROOT / 'TREX/dsp/ssi_crc.i').write_text('\n'.join(lines) + '\n')
    print('65536 word updates and signed DSP byte extractions verified; both tables generated')


if __name__ == '__main__':
    generate()
